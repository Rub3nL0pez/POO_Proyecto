    private void btnSiguienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSiguienteActionPerformed
        // TODO add your handling code here:
       // Doble clic al botón Siguiente
    if (motor.getNivelActual() <= 4) {
        // --- VALIDACIONES OBLIGATORIAS PARA PASAR EL TUTORIAL (NIVELES 1 AL 4) ---
        boolean puedePasar = false;
        String mensajeError = "";

        if (motor.getNivelActual() == 1) {
            puedePasar = motor.isEntradaA() && motor.isEntradaB();
            mensajeError = "Para pasar el tutorial de la AND debes lograr que la salida sea 1 (Prender el foco).";
        } 
        else if (motor.getNivelActual() == 2) {
            puedePasar = motor.isEntradaA() || motor.isEntradaB();
            mensajeError = "Para pasar el tutorial de la OR debes lograr que la salida sea 1 (Prender el foco).";
        } 
        else if (motor.getNivelActual() == 3) {
            puedePasar = !motor.isEntradaA();
            mensajeError = "Para pasar el tutorial de la NOT debes lograr que la salida sea 1 (Invertir el 0 de la Entrada A).";
        } 
        else if (motor.getNivelActual() == 4) {
            puedePasar = motor.isEntradaA() ^ motor.isEntradaB();
            mensajeError = "Para pasar el tutorial de la XOR debes lograr que las entradas sean diferentes para prender el foco.";
        }

        // Evaluamos si el alumno resolvió el tutorial actual
        if (!puedePasar) {
            JOptionPane.showMessageDialog(this, mensajeError, "Tutorial incompleto", JOptionPane.WARNING_MESSAGE);
        } else {
            // Si lo resolvió correctamente, avanzamos de nivel en el motor
            motor.siguienteNivel();
            motor.calcularResultadoInterno(); 
            
            // --- CORRECCIÓN CRUCIAL: USAMOS usuarioActual ---
            if (this.usuarioActual != null) {
                this.usuarioActual.setNivelActual(motor.getNivelActual());
                if (motor.getNivelActual() > this.usuarioActual.getNivelMaximo()) {
                    this.usuarioActual.setNivelMaximo(motor.getNivelActual());
                }
                // Guardamos el objeto global real que maneja la pantalla
                Memorycard.guardarOActualizarUsuario(this.usuarioActual); 
            }
            
            // Limpieza de estados visuales para el nuevo nivel
            respuestaTemporal = "";             
            compuertaOculta = 0;                
            actualizarTablero();                
        }
    } 
    else {
        // --- LÓGICA NORMAL PARA NIVELES 5 EN ADELANTE (PUZLES OCULTOS) ---
        if (motor.siguienteNivel()) {
            motor.calcularResultadoInterno(); 
            
            // --- CORRECCIÓN CRUCIAL: USAMOS usuarioActual ---
            if (this.usuarioActual != null) {
                this.usuarioActual.setNivelActual(motor.getNivelActual());
                if (motor.getNivelActual() > this.usuarioActual.getNivelMaximo()) {
                    this.usuarioActual.setNivelMaximo(motor.getNivelActual());
                }
                // Guardamos el progreso en el archivo
                Memorycard.guardarOActualizarUsuario(this.usuarioActual); 
            }
            
            // Limpieza de estados visuales
            respuestaTemporal = "";             
            compuertaOculta = 0;                
            actualizarTablero();                
        } else {
            JOptionPane.showMessageDialog(this, "Debes resolver el puzle actual y darle a 'Verificar' antes de poder avanzar.", "Nivel Bloqueado", JOptionPane.WARNING_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnSiguienteActionPerformed

