    private void btnVerificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerificarActionPerformed
        // TODO add your handling code here:
        // 1. Si está en niveles de tutorial (1 al 4), el botón verificar no hace falta
    if (motor.getNivelActual() <= 4) {
        JOptionPane.showMessageDialog(this, "En los niveles tutoriales debes interactuar con las entradas hasta activar la salida.", "Modo Tutorial", JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    // 2. Si el alumno le dio a verificar sin elegir nada, le frenamos el carro
    if (respuestaTemporal.equals("")) {
        JOptionPane.showMessageDialog(this, "Por favor, selecciona una compuerta de la derecha (AND, OR, XOR, NOT) antes de verificar.", "Ninguna selección", JOptionPane.WARNING_MESSAGE);
        return;
    }

    boolean esCorrecto = motor.evaluarRespuestaMatematica(respuestaTemporal, compuertaOculta);
    
    // 5. Mandamos el veredicto directo a tu motor. 
    int estadoJuego = motor.verificar(esCorrecto);

    // 6. Evaluamos la respuesta del motor para mostrar el cartel correcto
    switch (estadoJuego) {
        case 0: // ¡ACERTÓ EL PUZLE!
            JOptionPane.showMessageDialog(this, "¡Excelente! Descubriste la compuerta oculta correctamente.", "Puzle Resuelto", JOptionPane.INFORMATION_MESSAGE);
            respuestaTemporal = ""; // Limpiamos la selección para el próximo nivel
            break;
            
        case 1: // FALLÓ, pero todavía le quedan intentos/vidas
            JOptionPane.showMessageDialog(this, "Incorrecto. Esa compuerta no genera la combinación de salida del circuito. ¡Intenta de nuevo!", "Respuesta Incorrecta", JOptionPane.WARNING_MESSAGE);
            // NOTA: No limpiamos respuestaTemporal para que el alumno vea qué puso y pueda cambiarla
            break;
            
        case 2: // SE QUEDÓ SIN INTENTOS (El motor ya habrá reseteado el puzle internamente)
            JOptionPane.showMessageDialog(this, "¡Te quedaste sin intentos! El circuito ha sido reiniciado con un nuevo puzle.", "Puzle Reiniciado", JOptionPane.ERROR_MESSAGE);
            respuestaTemporal = ""; // Limpiamos la selección porque el puzle cambió por completo
            break;
            
        case 3: // PENALIZACIÓN MÁXIMA (El motor lo bajó de nivel)
            JOptionPane.showMessageDialog(this, "¡Racha negativa! Has descendido de nivel para repasar los conceptos básicos.", "Descenso de Nivel", JOptionPane.ERROR_MESSAGE);
            respuestaTemporal = ""; // Limpiamos la selección
            break;
    }

    // 7. Refrescamos toda la pantalla con los nuevos datos (intentos, niveles, etc.)
    actualizarTablero();
    }//GEN-LAST:event_btnVerificarActionPerformed

    private void lblEstadoAMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lblEstadoAMouseClicked

        // Invertimos el valor de la entrada A en el motor
        motor.setEntradaA(!motor.isEntradaA());
        // Si estamos en niveles tutoriales (1 a 4), evaluamos dinámicamente si ya resolvió el tutorial
        motor.calcularResultadoInterno();
        //Bloqueo
        if (motor.getNivelActual() > 4) {
        return; 
        }
        if (motor.getNivelActual() <= 4) {
        // En el nivel 1 (AND), el objetivo es que ambas sean 1
        if (motor.getNivelActual() == 1 && motor.isEntradaA() && motor.isEntradaB()) {
            JOptionPane.showMessageDialog(this, "¡Excelente! Lograste activar la compuerta AND. Ya puedes avanzar.");
        }
    }
    // Refrescamos la pantalla para ver el cambio reflejado
    actualizarTablero();
    }//GEN-LAST:event_lblEstadoAMouseClicked

