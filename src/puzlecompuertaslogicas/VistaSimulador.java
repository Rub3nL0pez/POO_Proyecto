private void actualizarTablero() {
    // --- PALETA DE COLORES MODO OSCURO / TECNOLÓGICO ---
    java.awt.Color colorON = new java.awt.Color(46, 204, 113);       // Verde Eléctrico (1)
    java.awt.Color colorOFF = new java.awt.Color(149, 165, 166);     // Gris Eléctrico Apagado (0)
    java.awt.Color colorFocoON = new java.awt.Color(241, 196, 15);   // Amarillo Foco encendido
    java.awt.Color colorFocoOFF = new java.awt.Color(44, 62, 80);    // Gris Oscuro Foco apagado
    java.awt.Color fondoCajaVisible = new java.awt.Color(52, 73, 94); // Azul Grisáceo para compuertas reveladas
    java.awt.Color colorMisterio = new java.awt.Color(155, 89, 182);   // Morado Tecnológico para la oculta

    // Oculta el botón verificar si está en los niveles tutoriales (1 al 4)
    if (motor.getNivelActual() <= 4) {
        btnVerificar.setVisible(false);
    } else {
        btnVerificar.setVisible(true);
    }
    
    // ===================================================
    // 1. MARCADOR DE CONTROL (NIVEL e INTENTOS)
    // ===================================================
    lblNivel.setText("Nivel Actual: " + motor.getNivelActual());
    lblNivel.setForeground(java.awt.Color.WHITE);
    
    lblIntentos.setText("Intentos Restantes: " + motor.getIntentosRestantes());
    if (motor.getIntentosRestantes() <= 1) {
        lblIntentos.setForeground(new java.awt.Color(231, 76, 60)); // Rojo peligro si le queda 1 vida
    } else {
        lblIntentos.setForeground(colorON);
    }
    
    // ===================================================
    // 2. ESTADOS DE LAS ENTRADAS (A, B, C, D) + COLORES
    // ===================================================
    // Asegurar contraste de las etiquetas de texto principales
    lblEstadoA.setForeground(java.awt.Color.WHITE);
    lblEstadoB.setForeground(java.awt.Color.WHITE);
    lblEstadoC.setForeground(java.awt.Color.WHITE);
    lblEstadoD.setForeground(java.awt.Color.WHITE);
    
    boolean estadoA = motor.isEntradaA();
    lblEstadoA.setText(estadoA ? "1 (ON)" : "0 (OFF)");
    lblEstadoA.setBackground(estadoA ? colorON : colorOFF);
    lblEstadoA.setOpaque(true);

    boolean estadoB = motor.isEntradaB();
    lblEstadoB.setText(estadoB ? "1 (ON)" : "0 (OFF)");
    lblEstadoB.setBackground(estadoB ? colorON : colorOFF);
    lblEstadoB.setOpaque(true);

    boolean estadoC = motor.isEntradaC();
    lblEstadoC.setText(estadoC ? "1 (ON)" : "0 (OFF)");
    lblEstadoC.setBackground(estadoC ? colorON : colorOFF);
    lblEstadoC.setOpaque(true);

    boolean estadoD = motor.isEntradaD();
    lblEstadoD.setText(estadoD ? "1 (ON)" : "0 (OFF)");
    lblEstadoD.setBackground(estadoD ? colorON : colorOFF);
    lblEstadoD.setOpaque(true);
    
    // ===================================================
    // 3. CONTROL DE VISIBILIDAD DE ENTRADAS Y COMPUERTAS
    // ===================================================
    if (motor.getNivelActual() == 3) { 
        // Nivel de la NOT: Solo mostramos la Entrada A
        lblEstadoA.setVisible(true);
        lblEstadoB.setVisible(false); 
        lblEstadoC.setVisible(false); 
        lblEstadoD.setVisible(false);
        lblCompuerta2.setVisible(false); // Ocultamos la de abajo
    } 
    else if (motor.getNivelActual() == 1 || motor.getNivelActual() == 2 || motor.getNivelActual() == 4) {
        // Otros niveles tutoriales de 2 entradas: Mostramos solo A y B
        lblEstadoA.setVisible(true);
        lblEstadoB.setVisible(true);
        lblEstadoC.setVisible(false);
        lblEstadoD.setVisible(false);
        lblCompuerta2.setVisible(false); // Ocultamos la de abajo
    } 
    else if (motor.getNivelActual() == 5 || motor.getNivelActual() == 6) {
        // Estructura en cascada (3 entradas): Usamos A, B y C. Ocultamos D y la Compuerta 2 (abajo).
        lblEstadoA.setVisible(true);
        lblEstadoC.setVisible(true);
        lblEstadoD.setVisible(false);    
        lblCompuerta2.setVisible(false); // ¡La de abajo desaparece físicamente!
        
        if (motor.getCompuertaActual() != null && "NOT".equalsIgnoreCase(motor.getCompuertaActual().getNombre())) {
            lblEstadoB.setVisible(false);
        } else {
            lblEstadoB.setVisible(true);
        }
    } 
    else {
        // Niveles avanzados de árbol (4 entradas): Mostramos todo
        lblEstadoA.setVisible(true);
        lblEstadoC.setVisible(true);
        lblCompuerta2.setVisible(true);  
        
        if (motor.getCompuertaActual() != null && "NOT".equalsIgnoreCase(motor.getCompuertaActual().getNombre())) {
            lblEstadoB.setVisible(false);
        } else {
            lblEstadoB.setVisible(true);
        }

        if (motor.getCompuertaAux1() != null && "NOT".equalsIgnoreCase(motor.getCompuertaAux1().getNombre())) {
            lblEstadoD.setVisible(false);
        } else {
            lblEstadoD.setVisible(true);
        }
    }

    // ===================================================
    // 4. ACTUALIZACIÓN AUTOMÁTICA DEL CABLEADO COBRA VIDA
    // ===================================================
    boolean salidaFinal = motor.isRespuestaEsperada();
    try {
        // Cables directos de las entradas
        if (findComponent("cableA") != null) getComponentByName("cableA").setForeground(estadoA ? colorON : colorOFF);
        if (findComponent("cableB") != null) getComponentByName("cableB").setForeground(estadoB ? colorON : colorOFF);
        if (findComponent("cableC") != null) getComponentByName("cableC").setForeground(estadoC ? colorON : colorOFF);
        if (findComponent("cableD") != null) getComponentByName("cableD").setForeground(estadoD ? colorON : colorOFF);
        
        // --- CABLES INTERMEDIOS Y FINALES ---
        // Cable Salida 1: Conecta la salida de la Compuerta 1 (Arriba) hacia adelante
        boolean señalSalida1 = false;
        if (motor.getCompuertaActual() != null) {
            String tipoComp1 = motor.getCompuertaActual().getNombre().toUpperCase().trim();
            switch (tipoComp1) {
                case "AND": señalSalida1 = estadoA && estadoB; break;
                case "OR":  señalSalida1 = estadoA || estadoB; break;
                case "XOR": señalSalida1 = estadoA ^ estadoB;  break;
                case "NOT": señalSalida1 = !estadoA;           break;
                default:    señalSalida1 = false;
            }
        }
        if (findComponent("cableSalida1") != null) {
            getComponentByName("cableSalida1").setForeground(señalSalida1 ? colorON : colorOFF);
        }
        
        // Cable Salida 2: Conecta la salida de la Compuerta 2 (Abajo) hacia adelante
        boolean señalSalida2 = false;
        if (motor.getCompuertaAux1() != null) {
            String tipoComp2 = motor.getCompuertaAux1().getNombre().toUpperCase().trim();
            switch (tipoComp2) {
                case "AND": señalSalida2 = estadoC && estadoD; break;
                case "OR":  señalSalida2 = estadoC || estadoD; break;
                case "XOR": señalSalida2 = estadoC ^ estadoD;  break;
                case "NOT": señalSalida2 = !estadoC;           break;
                default:    señalSalida2 = false;
            }
        }
        if (findComponent("cableSalida2") != null) {
            getComponentByName("cableSalida2").setForeground(señalSalida2 ? colorON : colorOFF);
        }
        // Cable Final: Conecta la compuerta final / misteriosa directo con el Foco de Salida
        if (findComponent("cableFinal") != null) {
            getComponentByName("cableFinal").setForeground(salidaFinal ? colorON : colorOFF);
        }
    } catch (Exception e) {
        // Silenciamos cualquier error reflectivo para que el juego siga corriendo sin problemas
    }
    
    // ===================================================
    // 5. EL FOCO DE SALIDA (ESTADO FINAL ENERGIZADO)
    // ===================================================
    // Fijamos tamaño robusto para evitar que Swing recorte el texto
    java.awt.Dimension tamFoco = new java.awt.Dimension(135, 30);
    lblFocoSalida.setPreferredSize(tamFoco);
    lblFocoSalida.setMinimumSize(tamFoco);
    lblFocoSalida.setMaximumSize(tamFoco);
    lblFocoSalida.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
    lblFocoSalida.setFont(new java.awt.Font("SansSerif", java.awt.Font.BOLD, 12));
    
    if (salidaFinal) {
        lblFocoSalida.setText(" 💡 ");
        lblFocoSalida.setBackground(colorFocoON);
        lblFocoSalida.setForeground(java.awt.Color.BLACK);
    } else {
        lblFocoSalida.setText(" ⚫ ");
        lblFocoSalida.setBackground(colorFocoOFF);
        lblFocoSalida.setForeground(java.awt.Color.WHITE);
    }
    lblFocoSalida.setOpaque(true);

    // ===================================================
    // 6. LÓGICA DE RENDICIÓN VISUAL RÍGIDA DE COMPUERTAS
    // ===================================================
    int lvlClave = motor.getNivelActual();

    if (compuertaOculta == 0) {
        if (histCompuertasOcultasVisual[lvlClave] != 0) {
            compuertaOculta = histCompuertasOcultasVisual[lvlClave];
        } else {
            if (lvlClave == 5 || lvlClave == 6) {
                compuertaOculta = 3; 
            } else {
                compuertaOculta = randMisterio.nextInt(3) + 1; 
            }
            histCompuertasOcultasVisual[lvlClave] = compuertaOculta;
        }
    }

    // --- RENDERIZADO SEGÚN EL TIPO DE NIVEL ---
    if (motor.getNivelActual() <= 4) {
        lblCompuerta1.setText(motor.getCompuertaActual() != null ? motor.getCompuertaActual().getNombre() : "---");
        lblCompuerta1.setBackground(fondoCajaVisible);
        lblCompuerta1.setForeground(java.awt.Color.WHITE);
        lblCompuerta1.setOpaque(true);
        
        lblCompuerta2.setText("---");
        lblCompuerta2.setBackground(colorFocoOFF);
        lblCompuerta2.setOpaque(true);
        
        lblCompuerta3.setText("---");
        lblCompuerta3.setBackground(colorFocoOFF);
        lblCompuerta3.setOpaque(true);
        
        lblCompuerta1.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
    } 
    else {
        // --- PREPARAMOS EL TEXTO DEL MISTERIO ---
        String textoMisterio = "[ ? ] MISTERIO";
        if (!respuestaTemporal.equals("")) {
            textoMisterio = "[ " + respuestaTemporal + " ] MISTERIO";
        }

        // --- TAMAÑOS INMUTABLES PARA EVITAR DESFASES ---
        java.awt.Dimension tamFijo = new java.awt.Dimension(140, 25);
        
        lblCompuerta1.setPreferredSize(tamFijo);
        lblCompuerta1.setMinimumSize(tamFijo);
        lblCompuerta1.setMaximumSize(tamFijo);
        lblCompuerta1.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        lblCompuerta1.setOpaque(true);

        lblCompuerta2.setPreferredSize(tamFijo);
        lblCompuerta2.setMinimumSize(tamFijo);
        lblCompuerta2.setMaximumSize(tamFijo);
        lblCompuerta2.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        lblCompuerta2.setOpaque(true);

        lblCompuerta3.setPreferredSize(tamFijo);
        lblCompuerta3.setMinimumSize(tamFijo);
        lblCompuerta3.setMaximumSize(tamFijo);
        lblCompuerta3.setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
        lblCompuerta3.setOpaque(true);

        // --- DIBUJADO ESTRICTO DE TEXTOS Y COLORES ---
        
        // Compuerta 1 (Arriba)
        if (compuertaOculta == 1) {
            lblCompuerta1.setText(textoMisterio);
            lblCompuerta1.setBackground(colorMisterio);
            lblCompuerta1.setForeground(java.awt.Color.WHITE);
        } else {
            lblCompuerta1.setText(motor.getCompuertaActual() != null ? motor.getCompuertaActual().getNombre() : "---");
            lblCompuerta1.setBackground(fondoCajaVisible);
            lblCompuerta1.setForeground(java.awt.Color.WHITE);
        }

        // Compuerta 2 (Abajo - Solo activa en niveles de árbol)
        if (compuertaOculta == 2) {
            lblCompuerta2.setText(textoMisterio);
            lblCompuerta2.setBackground(colorMisterio);
            lblCompuerta2.setForeground(java.awt.Color.WHITE);
        } else {
            lblCompuerta2.setText(motor.getCompuertaAux1() != null ? motor.getCompuertaAux1().getNombre() : "---");
            lblCompuerta2.setBackground(fondoCajaVisible);
            lblCompuerta2.setForeground(java.awt.Color.WHITE);
        }

        // Compuerta 3 (Derecha - Unión final)
        if (compuertaOculta == 3) {
            lblCompuerta3.setText(textoMisterio);
            lblCompuerta3.setBackground(colorMisterio);
            lblCompuerta3.setForeground(java.awt.Color.WHITE);
        } else {
            if (motor.getNivelActual() >= 7) {
                lblCompuerta3.setText(motor.getCompuertaAux2() != null ? motor.getCompuertaAux2().getNombre() : "---");
            } else {
                lblCompuerta3.setText(motor.getCompuertaAux1() != null ? motor.getCompuertaAux1().getNombre() : "---");
            }
            lblCompuerta3.setBackground(fondoCajaVisible);
            lblCompuerta3.setForeground(java.awt.Color.WHITE);
        }
    }
}

